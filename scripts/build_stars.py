def fnum(s: str) -> float:
    s = s.strip()
    if not s:
        return math.nan
    try:
        return float(s)
    except ValueError:
        return math.nan


def unit(ra_deg, dec_deg):
    ra, dec = np.radians(ra_deg), np.radians(dec_deg)
    cd = np.cos(dec)
    return np.stack([cd * np.cos(ra), cd * np.sin(ra), np.sin(dec)], axis=-1)


def cartesian(ra_deg, dec_deg, dist_pc, pmra_mas, pmdec_mas, rv_kms):
    """Position (pc) and velocity (pc/yr) in ICRS axes. pmra includes cos(dec)."""
    ra, dec = np.radians(ra_deg), np.radians(dec_deg)
    sr, cr, sd, cd = np.sin(ra), np.cos(ra), np.sin(dec), np.cos(dec)
    r_hat = np.stack([cd * cr, cd * sr, sd], axis=-1)
    e_ra = np.stack([-sr, cr, np.zeros_like(ra)], axis=-1)
    e_dec = np.stack([-sd * cr, -sd * sr, cd], axis=-1)
    d = np.asarray(dist_pc)[..., None]
    pos = r_hat * d
    vel = (e_ra * (np.asarray(pmra_mas) * MAS)[..., None] + e_dec * (np.asarray(pmdec_mas) * MAS)[..., None]) * d
    vel = vel + r_hat * (np.asarray(rv_kms) * KMS_TO_PCYR)[..., None]
    return pos, vel


def to_epoch(ra, dec, pmra, pmdec, epoch):
    """Move a sky position from `epoch` to EPOCH by proper motion (small-angle; fine for matching)."""
    dt = EPOCH - epoch
    dec2 = dec + pmdec * dt / 3.6e6
    ra2 = ra + pmra * dt / 3.6e6 / np.cos(np.radians(dec))
    return ra2 % 360.0, dec2


def radec(v):
    d = float(np.linalg.norm(v))
    return math.degrees(math.atan2(v[1], v[0])) % 360.0, math.degrees(math.asin(v[2] / d)), d


