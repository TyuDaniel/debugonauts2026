def spt_class(spt: str) -> str:
    s = re.sub(r"^(esd|usd|sd|d(?=[A-Z])|\[|\()", "", spt.strip())
    return s[:1].upper() if s else ""


def colour_from_spt(spt: str) -> float:
    c = spt_class(spt)
    for k, v in SPT_COLOUR:
        if c == k:
            if c == "M":
                m = re.search(r"M(\d+(\.\d+)?)", spt)
                sub = float(m.group(1)) if m else 3.0
                return 1.8 + 0.33 * sub
            return v
    return 2.6


def read_gcns():
    cols = {k: [] for k in ("id", "ra", "dec", "plx", "pmra", "pmdec", "rv", "g", "bp", "rp", "dist", "wd")}
    with open(GCNS, encoding="ascii", errors="replace") as fh:
        seen_header = False
        for line in fh:
            if line.startswith("#") or not line.strip():
                continue
            if not seen_header:
                seen_header = line.startswith("GaiaEDR3")
                continue
            p = line.rstrip("\n").split("\t")
            if len(p) < 13 or not p[0].strip().isdigit():
                continue
            cols["id"].append(int(p[0]))
            for key, i in (("ra", 1), ("dec", 2), ("plx", 3), ("pmra", 4), ("pmdec", 5), ("rv", 6),
                           ("g", 7), ("bp", 8), ("rp", 9), ("dist", 10), ("wd", 11)):
                cols[key].append(fnum(p[i]))
    out = {k: np.array(v, dtype=np.float64) for k, v in cols.items() if k != "id"}
    out["id"] = np.array(cols["id"], dtype=np.uint64)
    return out


def read_k24():
    """Census rows as dicts, with the '--' hierarchy resolved.

    A row is used when it has coordinates and a parallax and none of its components
    (rows nested under it) has coordinates of its own, so each object appears once.
    """
    rows = []
    with open(K24, encoding="utf-8", errors="replace") as fh:
        seen_header = False
        for line in fh:
            if line.startswith("#") or not line.strip():
                continue
            if not seen_header:
                seen_header = line.startswith("Name")
                continue
            p = line.rstrip("\n").split("\t")
            if len(p) < 14 or p[0].startswith("---------") or not p[0].strip():
                continue
            raw = p[0].rstrip()
            if raw.startswith('"'):  # TSV-quoted name with doubled inner quotes
                raw = raw.strip('"').replace('""', '"').rstrip()
            name = raw.lstrip("-")
            depth = (len(raw) - len(name)) // 2
            rows.append({
                "name": name.strip(), "depth": depth,
                "ra": fnum(p[1]), "dec": fnum(p[2]), "epoch": fnum(p[3]), "plx": fnum(p[4]),
                "pmra": fnum(p[5]), "pmdec": fnum(p[6]), "sopt": p[7].strip(), "snir": p[8].strip(),
                "code": fnum(p[9]), "g": fnum(p[10]), "w1": fnum(p[11]), "w2": fnum(p[12]), "j": fnum(p[13]),
            })
    has = [not math.isnan(r["ra"]) and not math.isnan(r["dec"]) for r in rows]
    used = []
    for i, r in enumerate(rows):
        if not has[i] or not (r["plx"] > 0):
            continue
        j = i + 1
        child_has = False
        while j < len(rows) and rows[j]["depth"] > r["depth"]:
            child_has = child_has or has[j]
            j += 1
        if child_has:
            continue
        # A blank spectral type on a system row: inherit from its components for display.
        if not r["sopt"] and not r["snir"]:
            kids = [rows[k] for k in range(i + 1, j)]
            types = [k["snir"] or k["sopt"] for k in kids if (k["snir"] or k["sopt"])]
            if types:
                r = dict(r, snir=" + ".join(types[:2]), code=max([k["code"] for k in kids if not math.isnan(k["code"])] or [math.nan]))
        used.append(r)
    blank = sum(1 for i, r in enumerate(rows) if not has[i])
    return used, len(rows), blank


def is_brown_dwarf(r) -> bool:
    spt = SPT_OVERRIDE.get(r["name"], "")
    types = [spt] if spt else [r["snir"], r["sopt"]]
    for t in types:
        for part in re.split(r"\s*\+\s*", t):
            if spt_class(part) in ("L", "T", "Y"):
                return True
    if r["code"] >= 50:
        return True
    # No published type, invisible to Gaia and very red in WISE: a cold brown dwarf.
    if not any(types) and math.isnan(r["g"]) and (r["w1"] - r["w2"]) > 1.0:
        return True
    return False


def main() -> int:
    print("reading GCNS ...")
    g = read_gcns()
    n_gcns = len(g["id"])
    print(f"  {n_gcns:,} rows")

    # Dist50 (posterior median distance) is tabulated to 0.01 pc, which is coarse for the nearest
    # stars (and reads 1.84 pc for Barnard's Star against 1.828 pc from its parallax). Where
    # 1/parallax agrees with Dist50 to 2 % the parallax is good, so use 1/parallax; where they
    # differ more the parallax is noisy and the posterior median is the better estimate.
    dist = g["dist"] * 1000.0
    inv = 1000.0 / np.where(g["plx"] > 0, g["plx"], np.nan)
    precise = ~(dist > 0) | (np.abs(inv - dist) < 0.02 * dist)
    dist = np.where(precise & np.isfinite(inv), inv, dist)
    rv_ok = ~np.isnan(g["rv"])
    rv = np.where(rv_ok, g["rv"], 0.0)
    pos, vel = cartesian(g["ra"], g["dec"], dist, g["pmra"], g["pmdec"], rv)

    gmag = g["g"].copy()
    mag_est = np.isnan(gmag)
    gmag[mag_est] = np.where(np.isnan(g["rp"][mag_est]), g["bp"][mag_est] - 1.5, g["rp"][mag_est] + 1.2)
    gmag[np.isnan(gmag)] = 18.0
    absmag = gmag - 5.0 * np.log10(dist / 10.0)

    colour = g["bp"] - g["rp"]
    col_est = np.isnan(colour)
    # Fill missing colours with the median colour of stars of the same absolute magnitude.
    bins = np.clip(np.floor(absmag * 2).astype(int), -10, 45)
    med = {}
    for b in np.unique(bins[col_est]):
        sel = (bins == b) & ~col_est
        med[b] = float(np.median(colour[sel])) if sel.sum() >= 5 else 2.5
    colour[col_est] = [med[b] for b in bins[col_est]]

    flags = np.zeros(n_gcns, dtype=np.uint8)
    flags[rv_ok] |= FLAG_RV
    flags[g["wd"] > 0.5] |= FLAG_WD
    flags[col_est] |= FLAG_COL_EST
    flags[mag_est] |= FLAG_MAG_EST
    print(f"  no radial velocity: {int((~rv_ok).sum()):,}; colour estimated: {int(col_est.sum()):,}; "
          f"G estimated: {int(mag_est.sum()):,}; white dwarfs: {int((g['wd'] > 0.5).sum()):,}")

    # Growable lists for the extra objects.
    x_pos, x_vel, x_abs, x_col, x_flag = [], [], [], [], []
    names: dict[int, dict] = {}  # star index -> {"n", "s", "a", ...}
    rv_measured = rv_ok.copy()

    # Sky lookup for matching against GCNS: only stars closer than 110 pc are relevant; use a
    # coarse grid on unit vectors so each lookup touches a handful of stars.
    u_gcns = pos / dist[:, None]
    app_gcns = gmag

    def nearest_gcns(u, radius_arcsec, sel):
        cosr = math.cos(math.radians(radius_arcsec / 3600.0))
        dots = u_gcns[sel] @ u
        hit = np.nonzero(dots > cosr)[0]
        return sel[hit], np.degrees(np.arccos(np.clip(dots[hit], -1, 1))) * 3600.0

    # ---- Hipparcos bright stars ------------------------------------------------------------
    bright_sel = np.nonzero(gmag < 6.5)[0]
    hip_added = hip_rv_new = hip_rv_gcns = hip_rv_none = 0
    hip_spt: dict[int, str] = {}   # star index -> XHIP spectral type
    x_rv: dict[int, float] = {}    # extra-star index -> XHIP radial velocity (km/s)
    hip_rows = [l.split(None, 11) for l in BRIGHT_HIP.strip().splitlines()]
    for row in hip_rows:
        hip = int(row[0])
        ra, dec, plx, pmra, pmdec, hp = map(float, row[1:7])
        bv = float(row[7]) if row[7] != "-" else 0.6
        rv_x = float(row[8]) if row[8] != "-" and row[10] in ("A", "B", "C") else None
        spt_x = row[11].strip() if row[11].strip() != "-" else ""
        d = 1000.0 / plx
        if d > 100.0:
            continue
        ra16, dec16 = to_epoch(ra, dec, pmra, pmdec, 1991.25)
        u = unit(ra16, dec16)
        idx, sep = nearest_gcns(u, 20.0, bright_sel)
        if len(idx):
            # Gaia has it. Keep the Gaia row; borrow the XHIP radial velocity if Gaia has none.
            gi = int(idx[np.argmin(gmag[idx])])
            if spt_x:
                hip_spt[gi] = spt_x
            if not rv_ok[gi]:
                if rv_x is not None:
                    vel[gi] += u_gcns[gi] * rv_x * KMS_TO_PCYR
                    flags[gi] |= FLAG_RV
                    rv_ok[gi] = True
                    hip_rv_gcns += 1
            continue
        p, v = cartesian(np.array(ra16), np.array(dec16), np.array(d), np.array(pmra), np.array(pmdec),
                         np.array(rv_x if rv_x is not None else 0.0))
        x_pos.append(p); x_vel.append(v)
        x_abs.append(hp - 5.0 * math.log10(d / 10.0))
        x_col.append(1.25 * bv + 0.02)
        fl = FLAG_EXTRA | FLAG_COL_EST | FLAG_MAG_EST
        if rv_x is not None:
            fl |= FLAG_RV
            x_rv[len(x_pos) - 1] = rv_x
            hip_rv_new += 1
        else:
            hip_rv_none += 1
        x_flag.append(fl)
        si = n_gcns + len(x_pos) - 1
        names[si] = {"n": f"HIP {hip}", "hp": round(hp, 2)}
        if spt_x:
            names[si]["s"] = spt_x
            hip_spt[si] = spt_x
        hip_added += 1
    print(f"XHIP bright stars: {len(hip_rows)} in table, {hip_added} missing from GCNS and added "
          f"({hip_rv_new} with XHIP radial velocity, {hip_rv_none} without); "
          f"XHIP radial velocity given to {hip_rv_gcns} GCNS stars that had none")

    def all_arrays():
        if x_pos:
            return (np.vstack([pos, np.array(x_pos)]), np.vstack([vel, np.array(x_vel)]),
                    np.concatenate([absmag, np.array(x_abs)]))
        return pos, vel, absmag

    # ---- 20-pc census ----------------------------------------------------------------------
    print("reading 20-pc census ...")
    k24, k_total, k_blank = read_k24()
    print(f"  {k_total:,} rows, {k_blank:,} with blank coordinates, {len(k24):,} usable objects")

    P, V, A = all_arrays()
    D = np.linalg.norm(P, axis=1)
    near = np.nonzero(D < 27.0)[0]
    U_near = P[near] / D[near, None]
    k_ra = np.array([r["ra"] for r in k24]); k_dec = np.array([r["dec"] for r in k24])
    k_ep = np.array([r["epoch"] if not math.isnan(r["epoch"]) else EPOCH for r in k24])
    k_pmra = np.nan_to_num(np.array([r["pmra"] for r in k24])); k_pmdec = np.nan_to_num(np.array([r["pmdec"] for r in k24]))
    k_ra16, k_dec16 = to_epoch(k_ra, k_dec, k_pmra, k_pmdec, k_ep)
    k_u = unit(k_ra16, k_dec16)
    k_d = 1000.0 / np.array([r["plx"] for r in k24])

    # Greedy one-to-one match by separation (<= 10 arcsec, distances agreeing within 30 %).
    pairs = []
    cos_lim = math.cos(math.radians(10.0 / 3600.0))
    for ki in range(len(k24)):
        dots = U_near @ k_u[ki]
        for h in np.nonzero(dots > cos_lim)[0]:
            if abs(D[near[h]] / k_d[ki] - 1.0) < 0.3:
                pairs.append((math.degrees(math.acos(min(1.0, dots[h]))) * 3600.0, ki, int(near[h])))
    pairs.sort()
    k_match: dict[int, int] = {}
    taken: set[int] = set()
    for sep, ki, si in pairs:
        if ki in k_match or si in taken:
            continue
        k_match[ki] = si
        taken.add(si)
    print(f"  matched to existing stars: {len(k_match):,}")

    bd_new = bd_in_gcns = star_new = 0
    extra_flags_gcns = {}
    for ki, r in enumerate(k24):
        spt = SPT_OVERRIDE.get(r["name"]) or r["snir"] or r["sopt"]
        if spt_class(r["sopt"]) not in ("L", "T", "Y", "") and r["sopt"] and not SPT_OVERRIDE.get(r["name"]):
            # Prefer the optical type for ordinary stars (the near-infrared one is often blank).
            spt = r["sopt"] if not is_brown_dwarf(r) else spt
        bd = is_brown_dwarf(r)
        entry = {"n": RENAME.get(r["name"], r["name"])}
        if entry["n"] != r["name"]:
            entry["a"] = r["name"]
        if spt:
            entry["s"] = spt
        for key in ("w1", "w2", "j"):
            if not math.isnan(r[key]) and bd:
                entry[key] = round(r[key], 2)
        if ki in k_match:
            si = k_match[ki]
            if si in names:  # a Hipparcos-added star: keep its Hp, take the better 2016 astrometry
                entry["hp"] = names[si]["hp"]
                entry.setdefault("a", names[si]["n"])
                xi = si - n_gcns
                p, v = cartesian(np.array(k_ra16[ki]), np.array(k_dec16[ki]), np.array(k_d[ki]),
                                 np.array(k_pmra[ki]), np.array(k_pmdec[ki]), np.array(x_rv.get(xi, 0.0)))
                x_pos[xi], x_vel[xi] = p, v
            names[si] = entry
            if bd:
                extra_flags_gcns[si] = FLAG_BD
                bd_in_gcns += 1
            continue
        # Not in GCNS: add it.
        p, v = cartesian(np.array(k_ra16[ki]), np.array(k_dec16[ki]), np.array(k_d[ki]),
                         np.array(k_pmra[ki]), np.array(k_pmdec[ki]), np.array(0.0))
        fl = FLAG_EXTRA | FLAG_COL_EST
        if not math.isnan(r["g"]):
            gm = r["g"]
            entry["g"] = round(gm, 2)
        else:
            fl |= FLAG_MAG_EST
            gm = r["j"] + (5.0 if bd else 2.7) if not math.isnan(r["j"]) else (
                r["w2"] + (9.0 if bd else 3.6) if not math.isnan(r["w2"]) else 20.0)
        if bd:
            fl |= FLAG_BD
            bd_new += 1
        else:
            star_new += 1
        if spt_class(spt) == "D":
            fl |= FLAG_WD
        x_pos.append(p); x_vel.append(v)
        x_abs.append(gm - 5.0 * math.log10(k_d[ki] / 10.0))
        x_col.append(colour_from_spt(spt) if spt else (5.0 if bd else 2.6))
        x_flag.append(fl)
        names[n_gcns + len(x_pos) - 1] = entry
    print(f"  brown dwarfs (L/T/Y): {bd_new} added, {bd_in_gcns} already in GCNS and flagged; "
          f"other census objects added: {star_new}")

    # ---- assemble --------------------------------------------------------------------------
    P, V, A = all_arrays()
    C = np.concatenate([colour, np.array(x_col)]) if x_col else colour
    F = np.concatenate([flags, np.array(x_flag, dtype=np.uint8)]) if x_flag else flags
    for si, fl in extra_flags_gcns.items():
        F[si] |= fl
    N = len(P)
    D = np.linalg.norm(P, axis=1)
    APP = A + 5.0 * np.log10(D / 10.0)

    # ---- famous names ----------------------------------------------------------------------
    U = P / D[:, None]
    bright = np.nonzero(APP < 6.5)[0]
    used: set[int] = set()
    for name, ra, dec in FAMOUS:
        dots = U[bright] @ unit(ra, dec)
        cand = [int(bright[h]) for h in np.nonzero(dots > math.cos(math.radians(0.15)))[0] if int(bright[h]) not in used]
        if not cand:
            print(f"  WARNING: famous star not found: {name}")
            continue
        si = min(cand, key=lambda s: APP[s])
        used.add(si)
        old = names.get(si, {})
        entry = dict(old)
        if old.get("n") and old["n"] != name:
            entry["a"] = old["n"] if not old.get("a") else f"{old['n']}, {old['a']}"
        entry["n"] = name
        if "s" not in entry and hip_spt.get(si):
            entry["s"] = hip_spt[si]
        names[si] = entry
    famous_idx = sorted(used)
    no_rv = [names[si]["n"] for si in famous_idx if not (F[si] & FLAG_RV)]
    print(f"famous names attached: {len(used)}; without a sourced radial velocity (drawn with zero): {no_rv}")

    by_name = {e["n"]: si for si, e in names.items()}
    for nm, rv_kms in EXTRA_RV.items():
        si = by_name[nm]
        if not (F[si] & FLAG_RV):
            V[si] = V[si] + U[si] * rv_kms * KMS_TO_PCYR
            F[si] |= FLAG_RV
    labels = []
    for nm in SHOWCASE_ON_MAP:
        if nm not in by_name:
            print(f"  ERROR: showcase target missing: {nm}")
            return 1
        labels.append({"i": by_name[nm], "k": "showcase"})
    seen_lab = set(l["i"] for l in labels)
    for nm in LABELS:
        si = by_name.get(nm)
        if si is None or si in seen_lab:
            continue
        if nm == "Luhman 16 A" and "Luhman 16 AB" in by_name:
            continue
        seen_lab.add(si)
        labels.append({"i": si, "k": "famous"})

    # ---- write -----------------------------------------------------------------------------
    OUT.mkdir(parents=True, exist_ok=True)
    header = struct.pack("<8sIIf12x", b"SKYSTAR1", N, n_gcns, EPOCH)
    assert len(header) == 32
    with open(OUT / "stars.bin", "wb") as fh:
        fh.write(header)
        fh.write(P.astype("<f4").tobytes())
        fh.write(V.astype("<f4").tobytes())
        fh.write(np.clip(np.round(A * 1000), -32000, 32000).astype("<i2").tobytes())
        fh.write(np.clip(np.round(C * 1000), -32000, 32000).astype("<i2").tobytes())
        fh.write(F.astype("u1").tobytes())
    (OUT / "stars-ids.bin").write_bytes(g["id"].astype("<u8").tobytes())

    named = [dict(i=si, **e) for si, e in sorted(names.items())]
    meta = {
        "about": "SkyDive 3D map sidecar. See scripts/build_stars.py for the stars.bin layout.",
        "epoch": EPOCH, "count": N, "n_gcns": n_gcns,
        "counts": {"gcns": n_gcns, "hipparcos_added": hip_added, "xhip_rv_used": hip_rv_new + hip_rv_gcns, "census_brown_dwarfs_added": bd_new,
                   "census_brown_dwarfs_in_gcns": bd_in_gcns, "census_other_added": star_new,
                   "brown_dwarfs": int((F & FLAG_BD).astype(bool).sum()), "named": len(named),
                   "no_radial_velocity": int((~(F & FLAG_RV).astype(bool)).sum())},
        "flags": {"rv": FLAG_RV, "brown_dwarf": FLAG_BD, "white_dwarf": FLAG_WD, "colour_estimated": FLAG_COL_EST,
                  "mag_estimated": FLAG_MAG_EST, "not_in_gcns": FLAG_EXTRA},
        "named": named, "labels": labels,
        "showcase": [{"n": nm, "i": by_name[nm]} for nm in SHOWCASE_ON_MAP] + [{"n": b["n"], "beyond": k} for k, b in enumerate(BEYOND)],
        "beyond": BEYOND, "regions": REGIONS,
    }
    (OUT / "stars-meta.json").write_text(json.dumps(meta, ensure_ascii=False, separators=(",", ":")), encoding="utf-8")

    size = (OUT / "stars.bin").stat().st_size
    print(f"\nwrote stars.bin  {size:,} bytes ({size / 1e6:.2f} MB)  N = {N:,}")
    print(f"wrote stars-ids.bin  {(OUT / 'stars-ids.bin').stat().st_size:,} bytes")
    print(f"wrote stars-meta.json  {(OUT / 'stars-meta.json').stat().st_size:,} bytes, {len(named):,} named, {len(labels)} labels")

    # ---- sanity checks ---------------------------------------------------------------------
    ok = True
    speed = np.linalg.norm(V, axis=1) / KMS_TO_PCYR
    print(f"\nspace speed km/s: median {np.median(speed):.1f}, 99th pct {np.percentile(speed, 99):.0f}, max {speed.max():.0f}")
    print(f"distance pc: min {D.min():.2f}, max {D.max():.1f}")
    if not np.isfinite(P).all() or not np.isfinite(V).all() or not np.isfinite(A).all() or not np.isfinite(C).all():
        print("ERROR: non-finite values"); ok = False

    b = by_name["Barnard's Star"]
    ra, dec, d = radec(P[b])
    print(f"Barnard's Star: {d:.3f} pc toward RA {ra:.3f}, Dec {dec:+.3f}; speed {speed[b]:.1f} km/s; "
          f"RV measured: {bool(F[b] & FLAG_RV)}")
    if not (abs(d - 1.83) < 0.005 and abs(ra - 269.45) < 0.02 and abs(dec - 4.74) < 0.05 and 80 < speed[b] < 160):
        print("ERROR: Barnard's Star sanity check failed"); ok = False
    ra2, dec2, _ = radec(P[b] + V[b] * (2026.87 - EPOCH))
    print(f"  at 2026.87: RA {ra2:.4f}, Dec {dec2:+.4f}")
    try:
        from astropy import units as u
        from astropy.coordinates import SkyCoord
        from astropy.time import Time
        gi = b
        c = SkyCoord(ra=g["ra"][gi] * u.deg, dec=g["dec"][gi] * u.deg, distance=dist[gi] * u.pc,
                     pm_ra_cosdec=g["pmra"][gi] * u.mas / u.yr, pm_dec=g["pmdec"][gi] * u.mas / u.yr,
                     radial_velocity=EXTRA_RV["Barnard's Star"] * u.km / u.s, obstime=Time(EPOCH, format="jyear"))
        c2 = c.apply_space_motion(Time(2026.87, format="jyear"))
        vx = c.velocity.d_xyz.to_value(u.pc / u.yr)
        print(f"  astropy check: 2026.87 RA {c2.ra.deg:.4f}, Dec {c2.dec.deg:+.4f}; "
              f"velocity difference {np.abs(vx - V[b]).max():.2e} pc/yr")
        if abs(c2.ra.deg - ra2) > 1e-4 or abs(c2.dec.deg - dec2) > 1e-4:
            print("ERROR: disagreement with astropy"); ok = False
    except Exception as exc:  # astropy is optional
        print(f"  (astropy check skipped: {exc})")
    for nm in ("WISE 0855−0714", "Epsilon Indi B", "Sirius", "Alpha Centauri A", "Proxima Centauri", "Vega"):
        if nm in by_name:
            s = by_name[nm]
            ra, dec, d = radec(P[s])
            print(f"{nm}: {d:.2f} pc, RA {ra:.3f}, Dec {dec:+.3f}, {speed[s]:.0f} km/s, app mag {APP[s]:.2f}, flags {int(F[s])}")
        else:
            print(f"WARNING: {nm} not present")
    return 0 if ok else 1


